"""Build report.html (Plotly panels) and report.xlsx (data + charts) from
a run directory's merged.csv (generated by merge.merge_run if not already
present).

Panels: Throughput, CPU breakdown (elbencho vs Lustre vs other), System
CPU, Memory, Network, and (milestone 3) a per-thread CPU panel. Each
panel groups merged rows by Metric, buckets ElapsedSec to whole seconds
(matching elbencho's --liveint 1000 / the 1s collectors), and draws one
line per (node, entity) - except Throughput and CPUBreakdown, which sum
across nodes onto one line per entity/category since the per-node
breakdown isn't the point of those panels (the per-node System CPU /
ThreadCPU panels are).

CPUBreakdown answers "what's actually consuming CPU" directly by
re-classifying pidstat ProcessCPU rows (see _classify_process) into
elbencho / Lustre client kernel threads / everything else, summed across
all nodes - instead of making people cross-reference the System CPU
panel (whole-node %user/%system/%idle) against the ThreadCPU panel
(top busiest threads by name) by hand.

The ThreadCPU panel is capped to the top THREAD_TOP_N (node, thread)
series by average %CPU, since a full pidstat -t capture can have
hundreds of threads and most are idle noise - this keeps the panel
focused on "which thread(s) is actually burning CPU" (the whole point of
shipping a per-thread view instead of making people dig through a flame
graph for that).
"""

from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple

from benchprof.merge import merge_run
from benchprof.schema import MetricRow, read_rows

THREAD_TOP_N = 15

# On a multi-node run a panel can easily end up with 30-100+ series (one
# per node/entity). Drawing them all visible at once, stacked on a shared
# legend, is what made the report "hard to read" - so each panel gets its
# own legend (positioned next to its row) and only its busiest
# VISIBLE_TOP_N series start visible; the rest start collapsed into the
# legend (click a legend entry to show that series) instead of being
# omitted outright.
VISIBLE_TOP_N = 8

# Process-name patterns used to classify pidstat ProcessCPU rows into the
# CPUBreakdown panel below, so "what's actually eating CPU" can be
# answered directly (elbencho vs Lustre client kernel threads vs
# everything else) instead of making people cross-reference the
# System CPU (sar, whole-node %user/%system/%idle) and ThreadCPU
# (top busiest threads by name) panels by hand.
_LUSTRE_PROCESS_PREFIXES = (
    "ptlrpcd", "ll_ost", "ll_sa", "ll_cfg", "ll_agl", "ldlm_bl", "ldlm_cb",
    "ldlm_cn", "osc_", "mdc_", "lov_", "lnet", "lquota", "kiblnd", "o2iblnd",
    "ll_imp_inval", "jbd2",
)


def _classify_process(command: str) -> str:
    c = command.lower()
    if "elbencho" in c:
        return "elbencho"
    if any(c.startswith(p) for p in _LUSTRE_PROCESS_PREFIXES):
        return "Lustre/filesystem"
    return "Other processes"


PANELS = [
    ("Throughput", "Throughput over time", "MiB/s"),
    ("CPUBreakdown", "CPU breakdown: elbencho vs Lustre vs other (summed across nodes)", "%"),
    ("CPU", "System CPU over time (per node)", "%"),
    ("Memory", "Memory usage over time", "%"),
    ("NetworkLink", "Network link throughput over time", "Gb/s"),
    ("ThreadCPU", f"Top {THREAD_TOP_N} threads by CPU over time", "%"),
]

# Panels whose series should be summed across all nodes onto one line per
# entity/category, rather than kept as one line per (node, entity) - these
# are cluster-wide aggregates where the per-node breakdown isn't the point
# (Throughput: total I/O rate; CPUBreakdown: total CPU time spent per
# category, which is directly comparable to Throughput's trend).
_SUM_ACROSS_NODES_METRICS = {"Throughput", "CPUBreakdown"}


def _bucket(rows: List[MetricRow], metric: str, sum_across_nodes: bool) -> Dict[str, Dict[float, float]]:
    """Returns {series_key: {elapsed_sec_bucket: value}}. series_key is
    `entity` when sum_across_nodes, else `node/entity`. For ThreadCPU,
    series are capped to the top THREAD_TOP_N by average value (see
    module docstring)."""
    series = defaultdict(lambda: defaultdict(float))
    # CPUBreakdown isn't its own metric in merged.csv - it's derived from
    # ProcessCPU rows (pidstat, one row per process per interval),
    # re-keyed by classifying the process's command name into a category.
    source_metric = "ProcessCPU" if metric == "CPUBreakdown" else metric
    for r in rows:
        if r.metric != source_metric:
            continue
        sec = round(r.elapsed_sec)
        entity = _classify_process(r.entity) if metric == "CPUBreakdown" else r.entity
        key = entity if sum_across_nodes else f"{r.node}/{entity}"
        series[key][sec] += r.value

    if metric == "ThreadCPU" and len(series) > THREAD_TOP_N:
        avg = {k: sum(v.values()) / len(v) for k, v in series.items()}
        top_keys = sorted(avg, key=avg.get, reverse=True)[:THREAD_TOP_N]
        series = {k: series[k] for k in top_keys}

    return series


def _warn_missing_sar(run_dir: Path) -> None:
    missing = sorted(p.name.split(".")[1] for p in (run_dir / "nodes").glob("*/sar.*.MISSING"))
    if missing:
        print(
            f"benchprof report: warning: sadc (sysstat) was not found on "
            f"{len(missing)} node(s) during collection "
            f"({', '.join(missing[:5])}{', ...' if len(missing) > 5 else ''}) - "
            "CPU/Memory sar panels will be empty for them."
        )


def _load_merged(run_dir: Path) -> List[MetricRow]:
    _warn_missing_sar(run_dir)
    merged_path = run_dir / "merged.csv"
    if not merged_path.exists():
        merge_run(run_dir)
    return read_rows(merged_path)


def build_html(run_dir, out_name: str = "report.html") -> Path:
    try:
        import plotly.graph_objects as go
        from plotly.subplots import make_subplots
        import plotly.io as pio
    except ImportError as e:
        raise SystemExit(
            "benchprof report: plotly is required for report.html "
            "(pip install -r requirements.txt)"
        ) from e

    run_dir = Path(run_dir)
    rows = _load_merged(run_dir)

    n = len(PANELS)
    fig = make_subplots(
        rows=n, cols=1, shared_xaxes=True,
        subplot_titles=[title for _, title, _ in PANELS],
        vertical_spacing=max(0.4 / n, 0.04),
    )

    legend_layout: Dict[str, dict] = {}
    for i, (metric, _title, unit) in enumerate(PANELS, start=1):
        sum_across_nodes = metric in _SUM_ACROSS_NODES_METRICS
        series = _bucket(rows, metric, sum_across_nodes)

        # Rank series by average value so the busiest ones are the ones
        # shown by default; the rest start hidden in the legend instead
        # of cluttering the plot (click to reveal).
        avg = {k: (sum(v.values()) / len(v) if v else 0.0) for k, v in series.items()}
        visible_keys = set(sorted(avg, key=avg.get, reverse=True)[:VISIBLE_TOP_N])

        legend_name = "legend" if i == 1 else f"legend{i}"
        yaxis_key = "yaxis" if i == 1 else f"yaxis{i}"
        domain = fig.layout[yaxis_key].domain  # [y0, y1] fraction of figure height for this row

        for key in sorted(series):
            pts = sorted(series[key].items())
            if not pts:
                continue
            xs, ys = zip(*pts)
            fig.add_trace(go.Scatter(
                x=list(xs), y=list(ys), mode="lines", name=key,
                legend=legend_name,
                visible=True if key in visible_keys else "legendonly",
            ), row=i, col=1)
        fig.update_yaxes(title_text=unit, row=i, col=1)

        legend_layout[legend_name] = dict(
            title=dict(text=metric + (" (top busiest shown)" if len(series) > VISIBLE_TOP_N else "")),
            y=domain[1], yanchor="top", x=1.02, xanchor="left",
            font=dict(size=10),
        )

    fig.update_layout(
        height=340 * n,
        title="benchprof report",
        xaxis_title="Elapsed (s)",
        hovermode="x unified",
        margin=dict(r=220),  # room for the per-panel legends on the right
        **legend_layout,
    )
    for ax in fig.select_xaxes():
        ax.update(matches="x")

    out_path = run_dir / out_name
    pio.write_html(fig, file=str(out_path), auto_open=False)
    print(f"Wrote {out_path}")
    return out_path


def build_xlsx(run_dir, out_name: str = "report.xlsx") -> Path:
    try:
        from openpyxl import Workbook
        from openpyxl.chart import LineChart, Reference
    except ImportError as e:
        raise SystemExit(
            "benchprof report: openpyxl is required for report.xlsx "
            "(pip install -r requirements.txt)"
        ) from e

    run_dir = Path(run_dir)
    rows = _load_merged(run_dir)

    wb = Workbook()
    data_ws = wb.active
    data_ws.title = "merged"
    data_ws.append(["Node", "Timestamp", "ElapsedSec", "Phase", "Source", "Metric", "Entity", "Value", "Unit"])
    for r in rows:
        data_ws.append(r.as_csv_row())

    for metric, title, unit in PANELS:
        sum_across_nodes = metric in _SUM_ACROSS_NODES_METRICS
        series = _bucket(rows, metric, sum_across_nodes)
        if not series:
            continue
        sheet_name = metric[:31]
        ws = wb.create_sheet(sheet_name)
        all_secs = sorted({sec for s in series.values() for sec in s})
        ws.append(["ElapsedSec"] + sorted(series.keys()))
        for sec in all_secs:
            ws.append([sec] + [series[k].get(sec, "") for k in sorted(series.keys())])

        chart = LineChart()
        chart.title = title
        chart.y_axis.title = unit
        chart.x_axis.title = "Elapsed (s)"
        n_rows = len(all_secs) + 1
        n_cols = len(series) + 1
        data_ref = Reference(ws, min_col=2, max_col=n_cols, min_row=1, max_row=n_rows)
        cats_ref = Reference(ws, min_col=1, min_row=2, max_row=n_rows)
        chart.add_data(data_ref, titles_from_data=True)
        chart.set_categories(cats_ref)
        ws.add_chart(chart, "A" + str(n_rows + 3))

    out_path = run_dir / out_name
    wb.save(out_path)
    print(f"Wrote {out_path}")
    return out_path


def build(run_dir) -> Tuple[Path, Path]:
    html_path = build_html(run_dir)
    xlsx_path = build_xlsx(run_dir)
    return html_path, xlsx_path
